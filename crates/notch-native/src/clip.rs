//! Clipboard đa nền tảng: đọc / ghi chữ, ảnh (PNG) và danh sách file.
//! macOS dùng NSPasteboard (đọc được cả file từ Finder, bỏ qua mục đánh dấu là mật khẩu).
//! Windows / Linux dùng arboard (chữ + ảnh).

#[derive(Debug, Clone, PartialEq)]
pub enum ClipData {
    Text(String),
    /// Ảnh dạng PNG
    Image(Vec<u8>),
    /// Đường dẫn tuyệt đối của file / thư mục
    Files(Vec<String>),
}

// ─────────────────────────── macOS ───────────────────────────
#[cfg(target_os = "macos")]
mod imp {
    #![allow(unused_unsafe)]
    use super::ClipData;
    use objc2::rc::Retained;
    use objc2::runtime::ProtocolObject;
    use objc2_app_kit::{
        NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardTypeFileURL, NSPasteboardTypePNG,
        NSPasteboardTypeString, NSPasteboardTypeTIFF, NSPasteboardWriting,
    };
    use objc2_foundation::{NSArray, NSData, NSDictionary, NSString, NSURL};
    use std::ffi::c_void;

    /// Các loại dữ liệu mà trình quản lý mật khẩu đánh dấu "đừng lưu lại"
    const PRIVATE_TYPES: &[&str] = &[
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard",
    ];

    pub fn change_count() -> i64 {
        unsafe { NSPasteboard::generalPasteboard().changeCount() as i64 }
    }

    pub fn read() -> Option<ClipData> {
        unsafe {
            let pb = NSPasteboard::generalPasteboard();
            let types: Vec<String> = pb.types()?.iter().map(|t| t.to_string()).collect();
            if types.iter().any(|t| PRIVATE_TYPES.contains(&t.as_str())) {
                return None;
            }
            // 1. File copy từ Finder
            if types.iter().any(|t| t == "public.file-url") {
                let mut files = vec![];
                if let Some(items) = pb.pasteboardItems() {
                    for it in items.iter() {
                        if let Some(s) = it.stringForType(NSPasteboardTypeFileURL) {
                            if let Some(url) = NSURL::URLWithString(&s) {
                                if let Some(p) = url.path() {
                                    files.push(p.to_string());
                                }
                            }
                        }
                    }
                }
                if !files.is_empty() {
                    return Some(ClipData::Files(files));
                }
            }
            // 2. Chữ (ưu tiên: copy ô Excel có cả ảnh lẫn chữ → lấy chữ)
            if let Some(s) = pb.stringForType(NSPasteboardTypeString) {
                let s = s.to_string();
                if !s.trim().is_empty() {
                    return Some(ClipData::Text(s));
                }
            }
            // 3. Ảnh
            if let Some(d) = pb.dataForType(NSPasteboardTypePNG) {
                return Some(ClipData::Image(d.to_vec()));
            }
            if let Some(d) = pb.dataForType(NSPasteboardTypeTIFF) {
                if let Some(rep) = NSBitmapImageRep::imageRepWithData(&d) {
                    let props = NSDictionary::new();
                    if let Some(png) = rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &props) {
                        return Some(ClipData::Image(png.to_vec()));
                    }
                }
            }
            None
        }
    }

    pub fn write(data: &ClipData) -> Result<(), String> {
        unsafe {
            let pb = NSPasteboard::generalPasteboard();
            pb.clearContents();
            let ok = match data {
                ClipData::Text(s) => pb.setString_forType(&NSString::from_str(s), NSPasteboardTypeString),
                ClipData::Image(png) => {
                    let d = NSData::with_bytes(png);
                    pb.setData_forType(Some(&d), NSPasteboardTypePNG)
                }
                ClipData::Files(paths) => {
                    let objs: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = paths
                        .iter()
                        .map(|p| ProtocolObject::from_retained(NSURL::fileURLWithPath(&NSString::from_str(p))))
                        .collect();
                    let arr = NSArray::from_retained_slice(&objs);
                    pb.writeObjects(&arr)
                }
            };
            if ok { Ok(()) } else { Err("Không ghi được vào clipboard".into()) }
        }
    }

    #[link(name = "CoreGraphics", kind = "framework")]
    extern "C" {
        fn CGEventSourceCreate(state: i32) -> *mut c_void;
        fn CGEventCreateKeyboardEvent(source: *mut c_void, key: u16, down: bool) -> *mut c_void;
        fn CGEventSetFlags(event: *mut c_void, flags: u64);
        fn CGEventPost(tap: u32, event: *mut c_void);
    }
    #[link(name = "CoreFoundation", kind = "framework")]
    extern "C" {
        fn CFRelease(p: *const c_void);
    }
    #[link(name = "ApplicationServices", kind = "framework")]
    extern "C" {
        fn AXIsProcessTrusted() -> bool;
    }

    /// Có quyền Trợ năng (Accessibility) để gửi phím ⌘V hộ người dùng không
    pub fn accessibility_trusted() -> bool {
        unsafe { AXIsProcessTrusted() }
    }

    /// Gửi ⌘V vào app đang đứng trước. Cần quyền Trợ năng.
    pub fn send_paste() -> bool {
        if !accessibility_trusted() {
            return false;
        }
        unsafe {
            let src = CGEventSourceCreate(1); // kCGEventSourceStateHIDSystemState
            const KEY_V: u16 = 9;
            const CMD: u64 = 0x0010_0000;
            for down in [true, false] {
                let ev = CGEventCreateKeyboardEvent(src, KEY_V, down);
                if ev.is_null() {
                    continue;
                }
                CGEventSetFlags(ev, CMD);
                CGEventPost(0, ev); // kCGHIDEventTap
                CFRelease(ev);
            }
            if !src.is_null() {
                CFRelease(src);
            }
        }
        true
    }
}

// ─────────────────────────── Windows / Linux ───────────────────────────
#[cfg(not(target_os = "macos"))]
mod imp {
    use super::ClipData;
    use std::hash::{Hash, Hasher};

    /// Không có bộ đếm thay đổi → dùng hash nội dung làm "phiên bản"
    pub fn change_count() -> i64 {
        let Ok(mut cb) = arboard::Clipboard::new() else { return 0 };
        let mut h = std::collections::hash_map::DefaultHasher::new();
        if let Ok(t) = cb.get_text() {
            t.hash(&mut h);
        } else if let Ok(img) = cb.get_image() {
            (img.width, img.height, img.bytes.len()).hash(&mut h);
            img.bytes.iter().step_by(997).for_each(|b| b.hash(&mut h));
        }
        h.finish() as i64
    }

    pub fn read() -> Option<ClipData> {
        let mut cb = arboard::Clipboard::new().ok()?;
        if let Ok(t) = cb.get_text() {
            if !t.trim().is_empty() {
                return Some(ClipData::Text(t));
            }
        }
        let img = cb.get_image().ok()?;
        let mut out = Vec::new();
        {
            let mut enc = png::Encoder::new(&mut out, img.width as u32, img.height as u32);
            enc.set_color(png::ColorType::Rgba);
            enc.set_depth(png::BitDepth::Eight);
            let mut w = enc.write_header().ok()?;
            w.write_image_data(&img.bytes).ok()?;
        }
        Some(ClipData::Image(out))
    }

    pub fn write(data: &ClipData) -> Result<(), String> {
        let mut cb = arboard::Clipboard::new().map_err(|e| e.to_string())?;
        match data {
            ClipData::Text(s) => cb.set_text(s.clone()).map_err(|e| e.to_string()),
            ClipData::Files(p) => cb.set_text(p.join("\n")).map_err(|e| e.to_string()),
            ClipData::Image(png_bytes) => {
                let dec = png::Decoder::new(std::io::Cursor::new(png_bytes));
                let mut r = dec.read_info().map_err(|e| e.to_string())?;
                let mut buf = vec![0; r.output_buffer_size()];
                let info = r.next_frame(&mut buf).map_err(|e| e.to_string())?;
                if info.color_type != png::ColorType::Rgba {
                    return Err("Chỉ hỗ trợ ảnh RGBA".into());
                }
                buf.truncate(info.buffer_size());
                cb.set_image(arboard::ImageData { width: info.width as usize, height: info.height as usize, bytes: buf.into() })
                    .map_err(|e| e.to_string())
            }
        }
    }

    pub fn accessibility_trusted() -> bool {
        false
    }

    pub fn send_paste() -> bool {
        false
    }
}

pub use imp::{accessibility_trusted, change_count, read, send_paste, write};
